CREATE TABLE exams (
                       id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                       name VARCHAR(150) NOT NULL,

                       code VARCHAR(50) NOT NULL UNIQUE,

                       category VARCHAR(50) NOT NULL,

                       conducting_body VARCHAR(150),

                       description TEXT,

                       official_website VARCHAR(500),

                       active BOOLEAN NOT NULL DEFAULT TRUE,

                       created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                       CONSTRAINT chk_exams_category CHECK (
                           category IN (
                                        'SCHOOL_BOARD',
                                        'ENGINEERING_ENTRANCE',
                                        'MEDICAL_ENTRANCE',
                                        'LAW_ENTRANCE',
                                        'MANAGEMENT_ENTRANCE',
                                        'UNIVERSITY_ENTRANCE',
                                        'POSTGRADUATE_ENTRANCE',
                                        'CENTRAL_GOVERNMENT',
                                        'STATE_GOVERNMENT',
                                        'CIVIL_SERVICES',
                                        'RAILWAY',
                                        'BANKING',
                                        'INSURANCE',
                                        'TEACHING_ELIGIBILITY',
                                        'POLICE_AND_PARAMILITARY',
                                        'DEFENCE',
                                        'JUDICIARY',
                                        'ENGINEERING_GOVERNMENT_JOBS',
                                        'TECHNICAL_GOVERNMENT_JOBS',
                                        'PUBLIC_SECTOR_UNDERTAKING',
                                        'STUDY_ABROAD',
                                        'PROFESSIONAL_CERTIFICATION',
                                        'OTHER'
                               )
                           )
);

CREATE INDEX idx_exams_name ON exams(name);

CREATE INDEX idx_exams_category ON exams(category);

CREATE INDEX idx_exams_active ON exams(active);