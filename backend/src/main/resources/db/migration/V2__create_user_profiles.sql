CREATE TABLE user_profiles (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                               user_id BIGINT NOT NULL,

                               education_level VARCHAR(40),

                               academic_stream VARCHAR(40),

                               learning_goal VARCHAR(50),

                               skill_level VARCHAR(30),

                               preparation_stage VARCHAR(30),

                               preferred_language VARCHAR(30),

                               preferred_mode VARCHAR(30),

                               onboarding_completed BOOLEAN NOT NULL DEFAULT FALSE,

                               created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

                               updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT uk_user_profile_user_id UNIQUE (user_id),

                               CONSTRAINT fk_user_profile_app_user
                                   FOREIGN KEY (user_id)
                                       REFERENCES app_users(id)
                                       ON DELETE CASCADE
);

CREATE INDEX idx_user_profiles_education_level
    ON user_profiles (education_level);

CREATE INDEX idx_user_profiles_learning_goal
    ON user_profiles (learning_goal);