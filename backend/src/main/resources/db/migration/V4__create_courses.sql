CREATE TABLE courses (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                         title VARCHAR(200) NOT NULL,

                         slug VARCHAR(220) NOT NULL UNIQUE,

                         description TEXT,

                         exam_id BIGINT NOT NULL,

                         instructor_name VARCHAR(150),

                         difficulty VARCHAR(30),

                         language VARCHAR(30),

                         thumbnail_url VARCHAR(500),

                         youtube_playlist_id VARCHAR(150),

                         active BOOLEAN NOT NULL DEFAULT TRUE,

                         created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT fk_courses_exam
                             FOREIGN KEY (exam_id)
                                 REFERENCES exams(id)
                                 ON DELETE RESTRICT,

                         CONSTRAINT chk_courses_difficulty
                             CHECK (
                                 difficulty IS NULL
                                     OR difficulty IN (
                                                       'COMPLETE_BEGINNER',
                                                       'BEGINNER',
                                                       'INTERMEDIATE',
                                                       'ADVANCED'
                                     )
                                 ),

                         CONSTRAINT chk_courses_language
                             CHECK (
                                 language IS NULL
                                 OR language IN (
                                 'ENGLISH',
                                 'HINDI',
                                 'HINGLISH',
                                 'REGIONAL'
                                 )
)
    );

CREATE INDEX idx_courses_exam_id
    ON courses(exam_id);

CREATE INDEX idx_courses_active
    ON courses(active);

CREATE INDEX idx_courses_title
    ON courses(title);