CREATE TABLE course_modules (
                                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                course_id BIGINT NOT NULL,

                                title VARCHAR(200) NOT NULL,

                                description TEXT,

                                sequence_number INTEGER NOT NULL,

                                published BOOLEAN NOT NULL DEFAULT FALSE,

                                created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                CONSTRAINT fk_course_modules_course
                                    FOREIGN KEY (course_id)
                                        REFERENCES courses(id)
                                        ON DELETE RESTRICT,

                                CONSTRAINT chk_course_modules_sequence
                                    CHECK (sequence_number > 0),

                                CONSTRAINT uq_course_modules_sequence
                                    UNIQUE (course_id, sequence_number)
);

CREATE INDEX idx_course_modules_course_id
    ON course_modules(course_id);

CREATE TABLE lectures (
                          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                          module_id BIGINT NOT NULL,

                          title VARCHAR(200) NOT NULL,

                          description TEXT,

                          youtube_video_id VARCHAR(50) NOT NULL,

                          duration_seconds INTEGER,

                          sequence_number INTEGER NOT NULL,

                          published BOOLEAN NOT NULL DEFAULT FALSE,

                          created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                          CONSTRAINT fk_lectures_module
                              FOREIGN KEY (module_id)
                                  REFERENCES course_modules(id)
                                  ON DELETE RESTRICT,

                          CONSTRAINT chk_lectures_sequence
                              CHECK (sequence_number > 0),

                          CONSTRAINT chk_lectures_duration
                              CHECK (
                                  duration_seconds IS NULL
                                      OR duration_seconds > 0
                                  ),

                          CONSTRAINT uq_lectures_sequence
                              UNIQUE (module_id, sequence_number)
);

CREATE INDEX idx_lectures_module_id
    ON lectures(module_id);